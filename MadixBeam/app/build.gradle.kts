// Release signing is read from keystore.properties (never committed) or from environment
// variables supplied by the CI secret store. Without them an unsigned release APK is built.
val signingProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

fun signingValue(key: String, environment: String): String? =
    signingProperties.getProperty(key) ?: System.getenv(environment)?.takeIf { it.isNotBlank() }

